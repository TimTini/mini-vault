const assert=require('node:assert/strict');
const fs=require('node:fs');
const {solveCode,Model,targets,mod}=require('../simulator/mechanism.js');
const desired=[8,4,12],before=desired.slice();
const result=solveCode(desired,1);
assert.deepEqual(desired,before,'preserve requested password');
assert.equal(result.tested,3375);
assert.deepEqual(result.holes,[0,1,6],'closest predicted contact readings for requested8/4/12');
assert.equal(result.matches,false,'never certify8/4/12 using ideal lookup or final-only accidental pickup');
assert.equal(result.measured,true);
assert.ok(Math.abs(result.predictedNumbers[0]-7.9091424081)<1e-7);
assert.ok(result.maxStopError>.25);
const m=new Model([0,1,6],1);
const exact=targets(m.low,m.high,false,-1).map(q=>mod(q)/22.5||16);
const solved=solveCode(exact,1);
assert.deepEqual(solved.holes,[0,1,6]);
assert.equal(solved.matches,true);
assert.ok(solved.maxStageError<1e-6);
const unsafe=new Model([14,14,14],1);
const unsafeNumbers=targets(unsafe.low,unsafe.high,false,-1).map(q=>mod(q)/22.5||16);
const blocked=solveCode(unsafeNumbers,1);
assert.equal(blocked.maxStopError,0,'matching contact readings alone are insufficient');
assert.equal(blocked.matches,false,'must reject re-pickup of parked disks');
assert.ok(blocked.maxStageError>20);
assert.equal(solveCode(desired,1.5).measured,false,'other scale must disclose estimated selected contacts');
assert.doesNotThrow(()=>solveCode([7,2,5],1),'inverse search must not reject input because chart has missing holes');
for(const invalid of [[NaN,4,12],[0,4,12],[17,4,12],[8,4]])assert.throws(()=>solveCode(invalid,1));
assert.throws(()=>solveCode([8,4,12],2));
assert.ok(!fs.readFileSync('simulator/app.js','utf8').includes('const selected=authorHoles(next)'),'runtime must solve desired code, not look up chart');
console.log('Verified inverse search, all3375 candidates, requested-code preservation, exact-stage control, unavailable chart numbers and input validation.');
